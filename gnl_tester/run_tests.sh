#!/usr/bin/env bash
# ============================================================================
#  run_tests.sh - get_next_line tester driver (MANDATORY part only)
#
#  Usage:   ./run_tests.sh [options]
#     --bs "1 42 4096"     BUFFER_SIZE values to test (default: a full list)
#     --modes "plain asan valgrind"   which runs to do (default: all available)
#     --level 0|1|2        0 = light, 1 = default, 2 = also 1 MB lines
#     --only B07           run a single test id (use with --bs and --modes plain)
#     --gnl-dir DIR        folder holding YOUR get_next_line.c/.h/_utils.c
#                          (default: the parent folder of this tester)
#  Env equivalents: BUFFER_SIZES, MODES, LEVEL, GNL_DIR, CC, VG_BS, OUT_DIR
# ============================================================================
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
GNL_DIR=${GNL_DIR:-"$HERE/.."}
CC=${CC:-cc}
BS_LIST=${BUFFER_SIZES:-"1 2 3 4 5 7 8 16 32 42 100 1024 4096 9999 10000000"}
BAD_LIST=${BAD_BUFFER_SIZES:-"0 -1"}
MODES=${MODES:-"plain asan valgrind"}
LEVEL=${LEVEL:-1}
VG_BS=${VG_BS:-"1 3 42 1024"}
ONLY=""

while [ $# -gt 0 ]; do
	case "$1" in
		--bs) BS_LIST=$2; BAD_LIST=""; shift 2 ;;
		--modes) MODES=$2; shift 2 ;;
		--level) LEVEL=$2; shift 2 ;;
		--only) ONLY=$2; BAD_LIST=""; shift 2 ;;
		--gnl-dir) GNL_DIR=$2; shift 2 ;;
		-h|--help) sed -n 2,14p "$0"; exit 0 ;;
		*) echo "unknown option: $1"; exit 2 ;;
	esac
done

if [ -t 1 ]; then G=$'\033[32m'; R=$'\033[31m'; Y=$'\033[33m'; B=$'\033[1m'; N=$'\033[0m'
else G=""; R=""; Y=""; B=""; N=""; fi

GNL_DIR=$(cd "$GNL_DIR" 2>/dev/null && pwd) || { echo "${R}GNL_DIR not found${N}"; exit 2; }
SRC_C="$GNL_DIR/get_next_line.c"; SRC_U="$GNL_DIR/get_next_line_utils.c"; SRC_H="$GNL_DIR/get_next_line.h"
for f in "$SRC_C" "$SRC_U" "$SRC_H"; do
	[ -f "$f" ] || { echo "${R}Missing $f${N}"
		echo "Put this tester folder inside your project (next to get_next_line.c),"
		echo "or run:  GNL_DIR=/path/to/your/project ./run_tests.sh"; exit 2; }
done

OUT=${OUT_DIR:-"$HERE"}
BUILD="$OUT/build"; RES="$OUT/results"
rm -rf "$BUILD" "$RES"; mkdir -p "$BUILD" "$RES"
: > "$RES/all.tsv"; : > "$RES/builds.txt"; : > "$RES/static.txt"
STATIC_FAIL=0

say() { printf '%s\n' "$*"; }
sp()  { printf '%s\n' "$*" | tee -a "$RES/static.txt"; }

# ---------------------------------------------------------------- static checks
say "${B}== 1. Static / compilation checks (subject rules) ==${N}"
CF="-Wall -Wextra -Werror"
chk() { # name, command...
	local name=$1; shift
	if out=$("$@" 2>&1); then sp "  ${G}PASS${N}  $name"
	else sp "  ${R}FAIL${N}  $name"; STATIC_FAIL=$((STATIC_FAIL+1)); printf '%s\n' "$out" | head -8 | sed 's/^/         | /' | tee -a "$RES/static.txt"; fi
}
chk "get_next_line.c compiles WITHOUT -D BUFFER_SIZE ($CF)" $CC $CF -I"$GNL_DIR" -c "$SRC_C" -o "$BUILD/s1.o"
chk "get_next_line_utils.c compiles WITHOUT -D BUFFER_SIZE ($CF)" $CC $CF -I"$GNL_DIR" -c "$SRC_U" -o "$BUILD/s2.o"
chk "header has include guards and works when included twice" $CC $CF -I"$GNL_DIR" -c "$HERE/src/header_check.c" -o "$BUILD/s3.o"
chk "compiles with -D BUFFER_SIZE=42 ($CF)" $CC $CF -DBUFFER_SIZE=42 -I"$GNL_DIR" -c "$SRC_C" -o "$BUILD/s4.o"

if grep -nE '#[[:space:]]*include[[:space:]]*["<]libft' "$GNL_DIR"/get_next_line*.[ch] >/dev/null 2>&1; then
	sp "  ${R}FAIL${N}  libft is forbidden (found an #include of libft)"; STATIC_FAIL=$((STATIC_FAIL+1))
else sp "  ${G}PASS${N}  no libft include"; fi

if command -v nm >/dev/null 2>&1; then
	allowed=" read malloc free "
	bad=""
	defd=" $(for o in "$BUILD/s1.o" "$BUILD/s2.o"; do nm --defined-only "$o" 2>/dev/null | awk '{print $NF}' | sed 's/^_//'; done | sort -u | tr '\n' ' ') "
	for o in "$BUILD/s1.o" "$BUILD/s2.o"; do
		for sym in $(nm -u "$o" 2>/dev/null | awk '{print $NF}' | sed 's/^_//; s/@.*//' | sort -u); do
			case "$sym" in
				__stack_chk_fail|_stack_chk_fail|stack_chk_fail|_stack_chk_guard|stack_chk_guard|_GLOBAL_OFFSET_TABLE_|GLOBAL_OFFSET_TABLE_|__gmon_start__|dyld_stub_binder) ;;
				*) case "$allowed$defd" in *" $sym "*) ;; *) bad="$bad $sym" ;; esac ;;
			esac
		done
	done
	bad=$(printf '%s\n' $bad | sort -u | tr '\n' ' ')
	if [ -z "${bad// /}" ]; then sp "  ${G}PASS${N}  only read/malloc/free are used (nm -u)"
	else sp "  ${R}FAIL${N}  forbidden function(s) referenced: $bad"
		case "$bad" in *memcpy*|*memset*|*memmove*) sp "         (memcpy/memset/memmove can be generated by the compiler for struct copies or array init - check your code)";; esac
		STATIC_FAIL=$((STATIC_FAIL+1)); fi
	gv=""
	for o in "$BUILD/s1.o" "$BUILD/s2.o"; do
		gv="$gv $(nm "$o" 2>/dev/null | awk '$2 ~ /^[BDCGSR]$/ {print $3}' | sed 's/^_//')"
	done
	if [ -z "${gv// /}" ]; then sp "  ${G}PASS${N}  no global variable (nm: only 'static' data)"
	else sp "  ${R}FAIL${N}  global variable(s) found (forbidden): $gv"; STATIC_FAIL=$((STATIC_FAIL+1)); fi
else sp "  ${Y}SKIP${N}  nm not found: forbidden-function / global-variable checks not done"; fi

if command -v norminette >/dev/null 2>&1; then
	if nm_out=$(norminette "$SRC_C" "$SRC_U" "$SRC_H" 2>&1) && ! printf '%s' "$nm_out" | grep -q 'Error'; then
		sp "  ${G}PASS${N}  norminette (informational)"
	else sp "  ${Y}INFO${N}  norminette reports problems (informational, not counted):"
		printf '%s\n' "$nm_out" | grep -v ': OK!' | head -6 | sed 's/^/         | /' | tee -a "$RES/static.txt"; fi
else sp "  ${Y}SKIP${N}  norminette not installed (not counted)"; fi

# ---------------------------------------------------------------- tool probes
HAVE_ASAN=0; ASAN_LEAKS=1
printf 'int main(void){return 0;}\n' > "$BUILD/probe.c"
if $CC -fsanitize=address,undefined "$BUILD/probe.c" -o "$BUILD/probe" >/dev/null 2>&1 && "$BUILD/probe" >/dev/null 2>&1; then
	HAVE_ASAN=1
	ASAN_OPTIONS=detect_leaks=1 "$BUILD/probe" >/dev/null 2>&1 || ASAN_LEAKS=0
fi
HAVE_VG=0; command -v valgrind >/dev/null 2>&1 && HAVE_VG=1

# ---------------------------------------------------------------- build / run
build() { # bs flavor(plain|asan|bad) -> prints binary path or returns 1
	local bs=$1 fl=$2 tag="${2}_${1}" san="" extra="" werr="-Werror"
	[ "$fl" = asan ] && san="-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer"
	[ "$fl" = bad ] && { extra="-DGNL_BADBS"; werr=""; }
	local f="-g -O0 -Wall -Wextra $werr $san -DBUFFER_SIZE=$bs -I$GNL_DIR"
	local log="$BUILD/$tag.log"
	{ $CC $f -include "$HERE/src/gnlt_hook.h" -c "$SRC_C" -o "$BUILD/c_$tag.o" &&
	  $CC $f -include "$HERE/src/gnlt_hook.h" -c "$SRC_U" -o "$BUILD/u_$tag.o" &&
	  $CC -g -O0 -Wall -Wextra $san $extra -DBUFFER_SIZE=$bs -I"$GNL_DIR" -c "$HERE/src/harness.c" -o "$BUILD/h_$tag.o" &&
	  $CC $san -o "$BUILD/t_$tag" "$BUILD/c_$tag.o" "$BUILD/u_$tag.o" "$BUILD/h_$tag.o"; } > "$log" 2>&1
	local rc=$?
	if [ $rc -ne 0 ]; then
		printf '%s\t%s\t%s\n' "$bs" "$fl" "$(head -c 400 "$log" | tr '\n\t' '  ')" >> "$RES/builds.txt"
		return 1
	fi
	return 0
}

run_one() { # bs mode
	local bs=$1 mode=$2 fl=$2 lvl=$LEVEL args="" mult=1
	[ "$mode" = valgrind ] && fl=plain
	[ "$mode" = bad ] && fl=bad
	local tag="${fl}_${bs}" tsv="$RES/${mode}_bs${bs}.tsv" log="$RES/${mode}_bs${bs}.log"
	[ -x "$BUILD/t_$tag" ] || build "$bs" "$fl" || { printf '  BS=%-9s %-9s %sBUILD FAILED%s (see %s)\n' "$bs" "$mode" "$R" "$N" "build/$tag.log"; return; }
	[ -n "$ONLY" ] && args="--only $ONLY"
	local prefix=""
	case "$mode" in
		asan) mult=3
			export ASAN_OPTIONS="exitcode=99:detect_leaks=$ASAN_LEAKS:abort_on_error=0"
			export UBSAN_OPTIONS="print_stacktrace=1:exitcode=99:halt_on_error=1" ;;
		valgrind) mult=15; lvl=0
			prefix="valgrind --quiet --error-exitcode=99 --leak-check=full --errors-for-leak-kinds=definite,indirect --track-origins=no" ;;
	esac
	GNL_TIMEOUT_MULT=$mult $prefix "$BUILD/t_$tag" --level "$lvl" --tsv "$tsv" $args > "$log" 2>&1
	local line; line=$(grep '^---- summary' "$log" | sed 's/---- summary (BUFFER_SIZE=[-0-9]*): //; s/ ----//')
	[ -z "$line" ] && line="${R}harness did not finish (see $log)${N}"
	local nbad; nbad=$(grep -c '^\(FAIL\|CRASH\|TIMEOUT\|SAN\)' "$log")
	local col=$G; [ "$nbad" -gt 0 ] && col=$R
	printf '  BS=%-9s %-9s %s%s%s\n' "$bs" "$mode" "$col" "$line" "$N"
	[ -s "$tsv" ] && awk -F'\t' -v OFS='\t' -v m="$mode" -v b="$bs" '{print m,b,$0}' "$tsv" >> "$RES/all.tsv"
}

say ""
say "${B}== 2. Dynamic tests (each test runs in its own process) ==${N}"
say "   tester: $HERE   |   your files: $GNL_DIR"
[ $HAVE_ASAN -eq 1 ] || say "   ${Y}AddressSanitizer not usable with '$CC' - asan runs skipped${N}"
[ $HAVE_ASAN -eq 1 ] && [ $ASAN_LEAKS -eq 0 ] && say "   ${Y}LeakSanitizer unusable here (ptrace restricted?) - leaks are still caught by the tester's own accounting${N}"
for mode in $MODES; do
	case "$mode" in
		asan) [ $HAVE_ASAN -eq 1 ] || continue ;;
		valgrind) [ $HAVE_VG -eq 1 ] || { say "   ${Y}valgrind not installed - valgrind run skipped (sudo apt install valgrind)${N}"; continue; } ;;
	esac
	say "-- mode: $mode"
	if [ "$mode" = valgrind ]; then list=$VG_BS; else list=$BS_LIST; fi
	for bs in $list; do run_one "$bs" "$mode"; done
done
if [ -n "$BAD_LIST" ] && printf '%s' "$MODES" | grep -q plain; then
	say "-- mode: bad BUFFER_SIZE (robustness only; the subject does not define it)"
	for bs in $BAD_LIST; do
		case "$bs" in -*) bsarg="$bs" ;; *) bsarg="$bs" ;; esac
		if build "$bsarg" bad; then
			tag="bad_$bsarg"; tsv="$RES/bad_bs${bsarg}.tsv"; log="$RES/bad_bs${bsarg}.log"
			GNL_TIMEOUT_MULT=1 "$BUILD/t_$tag" --level 0 --tsv "$tsv" > "$log" 2>&1
			line=$(grep '^---- summary' "$log" | sed 's/---- summary (BUFFER_SIZE=[-0-9]*): //; s/ ----//')
			nbad=$(grep -c '^\(FAIL\|CRASH\|TIMEOUT\|SAN\)' "$log"); col=$G; [ "$nbad" -gt 0 ] && col=$R
			printf '  BS=%-9s %-9s %s%s%s\n' "$bsarg" "bad" "$col" "$line" "$N"
			[ -s "$tsv" ] && awk -F'\t' -v OFS='\t' -v m="bad" -v b="$bsarg" '{print m,b,$0}' "$tsv" >> "$RES/all.tsv"
		else
			printf '  BS=%-9s %-9s %sdoes not compile%s with this BUFFER_SIZE (robustness only)\n' "$bsarg" "bad" "$Y" "$N"
			printf '%s\tbad\tdoes not compile\n' "$bsarg" >> "$RES/builds.txt"
		fi
	done
fi

# ---------------------------------------------------------------- report
say ""
say "${B}== 3. Report ==${N}"
awk -F'\t' -v G="$G" -v R="$R" -v B="$B" -v N="$N" -v sfail="$STATIC_FAIL" '
BEGIN {
	cn[0]="Basic functionality"; cn[1]="Buffer boundaries"; cn[2]="Advanced content"
	cn[3]="EOF behavior"; cn[4]="File descriptor and error handling"; cn[5]="Memory management"
}
{
	mode=$1; bs=$2; st=$3; m=$4; cat=$5; id=$6; name=$7; rs=$9
	key = bs SUBSEP id
	if (!(key in seen)) { seen[key]=1; tot[cat]++; kcat[key]=cat }
	if (st != "PASS") {
		if (!(key in bad)) {
			bad[key]=1; nb[cat]++
			if (!(id in fid)) { fid[id]=1; order[++no]=id; fm[id]=m; fn[id]=name; fst[id]=st; fr[id]=rs; fbs1[id]=bs; fmode1[id]=mode }
			fbs[id] = fbs[id] (fbs[id]=="" ? "" : ",") bs
		}
		if (index(fmodes[id], mode) == 0) fmodes[id] = fmodes[id] (fmodes[id]=="" ? "" : ",") mode
		if (st == "SAN" || st == "CRASH" || index(rs, "[MEM]") == 1) mem[mode]++
	}
}
END {
	printf "\n| Category | Tests | Passed | Failed |\n|---|---:|---:|---:|\n"
	T=0; F=0
	for (c=0;c<6;c++) { t=tot[c]+0; f=nb[c]+0; T+=t; F+=f; printf "| %s | %d | %d | %d |\n", cn[c], t, t-f, f }
	printf "| Helper functions | - | - | - |   (template: src/helpers_test.c - see README)\n"
	printf "| **Total** | %d | %d | %d |\n\n", T, T-F, F
	printf "(a \"test\" = one test id at one BUFFER_SIZE; it counts as failed if it failed in ANY run: plain / asan / valgrind)\n\n"
	nm=0; nr=0
	for (i=1;i<=no;i++) { id=order[i]; if (fm[id]=="M") nm++; else nr++ }
	if (no == 0) printf "%sNo failing test.%s\n", G, N
	else {
		printf "%sFailures (grouped by test, ordered by id):%s\n", B, N
		lim = (no > 25 ? 25 : no)
		for (i=1;i<=no;i++) {
			if (i > lim) { printf "\n ... and %d more failing tests (all of them are listed in results/all.tsv)\n", no - lim; break }
			id=order[i]
			printf "\n %s[%s]%s %s %s\n", R, (fm[id]=="M" ? "MANDATORY" : "ROBUSTNESS"), N, id, fn[id]
			printf "     fails at BUFFER_SIZE = %s   (runs: %s, status: %s)\n", fbs[id], fmodes[id], fst[id]
			printf "     reason (BS=%s, %s): %s\n", fbs1[id], fmode1[id], fr[id]
			printf "     full details: results/%s_bs%s.log\n", fmode1[id], fbs1[id]
		}
	}
	printf "\n%sMemory tools:%s findings (sanitizer/valgrind errors, crashes, [MEM] leaks) per run type:", B, N
	any=0; for (k in mem) { printf "  %s=%d", k, mem[k]; any=1 }
	if (!any) printf "  none"
	printf "\n\n"
	printf "Distinct failing tests: %d mandatory, %d robustness-only.  Static-check failures: %d\n", nm, nr, sfail
	if (nm == 0 && sfail == 0) printf "%sNo mandatory failure detected in the configurations that were executed.%s (This is evidence, not proof - see README for what the suite cannot cover.)\n", G, N
	else printf "%sNOT ready for evaluation: fix the mandatory failures above first.%s\n", R, N
}' "$RES/all.tsv" | tee "$RES/report.txt"
if [ -s "$RES/builds.txt" ]; then
	say ""; say "${Y}Build problems:${N}"; sed 's/^/  /' "$RES/builds.txt"
fi
say ""
say "Per-run logs: $RES/<mode>_bs<N>.log   |   one test only: ./run_tests.sh --bs 5 --modes plain --only B07"
